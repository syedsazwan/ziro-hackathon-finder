def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def _format_sql_value(val: Any) -> str:
    if val is None:
        return "NULL"
    if isinstance(val, bool):
        return "1" if val else "0"
    if isinstance(val, (int, float)):
        return str(val)
    if isinstance(val, str):
        escaped = val.replace("'", "''")
        return f"'{escaped}'"
    escaped = str(val).replace("'", "''")
    return f"'{escaped}'"


def _parse_ddl_columns() -> Dict[str, List[str]]:
    create_table_blocks = re.findall(
        r'CREATE TABLE IF NOT EXISTS\s+([a-zA-Z0-9_]+)\s*\((.*?)\);',
        DDL_STATEMENTS,
        re.DOTALL | re.IGNORECASE
    )
    table_defs = {}
    for tbl_name, body in create_table_blocks:
        cols = []
        for line in body.splitlines():
            line = line.strip()
            if not line or line.startswith("--"):
                continue
            if line.upper().startswith(("UNIQUE", "PRIMARY KEY", "CONSTRAINT", "FOREIGN KEY", "CHECK")):
                continue
            col_name = line.split()[0].replace('"', '')
            cols.append(col_name)
        table_defs[tbl_name] = cols
    return table_defs


def generate_migration_sql():
    if not DB_PATH.exists():
        raise FileNotFoundError(f"Source database not found: {DB_PATH}")

    hash_before = _sha256(DB_PATH)

    uri = f"file:{DB_PATH.resolve().as_posix()}?mode=ro"
    conn = sqlite3.connect(uri, uri=True)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()

    # Collect sqlite sequence values
    sqlite_sequences: Dict[str, int] = {}
    try:
        cur.execute("SELECT name, seq FROM sqlite_sequence;")
        for name, seq in cur.fetchall():
            sqlite_sequences[name] = seq
    except Exception:
        pass

    ddl_columns = _parse_ddl_columns()

    sql_lines: List[str] = []
    sql_lines.append("-- ============================================================================")
    sql_lines.append("-- ZIRO — PRODUCTION MIGRATION SCRIPT FOR NEON POSTGRESQL")
    sql_lines.append("-- Generated from backend/events.db (read-only source)")
    sql_lines.append("-- Guarantees: Full relational parity, idempotent, safe to retry, zero partial state")
    sql_lines.append("-- ============================================================================\n")
    sql_lines.append("BEGIN;\n")
    sql_lines.append("-- Explicitly target the public schema in Neon")
    sql_lines.append("SET search_path = public;\n")
    sql_lines.append(DDL_STATEMENTS.strip())
    sql_lines.append("\n-- ============================================================================")
    sql_lines.append("-- 2. DATA INSERTION (Idempotent: ON CONFLICT DO NOTHING)")
    sql_lines.append("-- ============================================================================\n")

    summary_stats = []
    total_rows = 0

    for table_name, pk_col in TABLE_MIGRATION_ORDER:
        # Check if table exists
        cur.execute("SELECT name FROM sqlite_master WHERE type='table' AND name = ?;", (table_name,))
        if not cur.fetchone():
            continue

        # Get column names aligned with PostgreSQL DDL definition
        columns = ddl_columns.get(table_name)
        if not columns:
            cur.execute(f'PRAGMA table_info("{table_name}");')
            columns = [c[1] for c in cur.fetchall()]
        cols_quoted = ", ".join(f'"{c}"' for c in columns)

        # Get rows
        cur.execute(f'SELECT * FROM "{table_name}" ORDER BY "{pk_col}" ASC;')

        rows = cur.fetchall()
        count = len(rows)
        total_rows += count
        summary_stats.append((table_name, count))

        sql_lines.append(f"-- Table: {table_name} ({count} rows)")
        if count == 0:
            sql_lines.append(f"-- (No rows to insert for {table_name})\n")
            continue

        # Chunk inserts in batches of 50 for readability and Neon editor performance
        batch_size = 50
        for i in range(0, count, batch_size):
            batch = rows[i:i + batch_size]
            sql_lines.append(f'INSERT INTO "{table_name}" ({cols_quoted}) VALUES')
            val_clauses = []
            for r in batch:
                vals = [_format_sql_value(r[c]) for c in columns]
                val_clauses.append("    (" + ", ".join(vals) + ")")
            sql_lines.append(",\n".join(val_clauses))
            sql_lines.append(f'ON CONFLICT ("{pk_col}") DO NOTHING;\n')

    # Sequence synchronization
    sql_lines.append("-- ============================================================================")
    sql_lines.append("-- 3. IDENTITY SEQUENCE SYNCHRONIZATION")
    sql_lines.append("-- ============================================================================\n")
    for table_name in TABLE_MIGRATION_ORDER:
        tbl = table_name[0]
        if tbl in TABLES_WITH_IDENTITY:
            seq_val = sqlite_sequences.get(tbl, 0)
            sql_lines.append(f"""SELECT setval(
    pg_get_serial_sequence('{tbl}', 'id'),
    GREATEST(COALESCE((SELECT MAX(id) FROM "{tbl}"), 0), {seq_val}),
    true
);""")

    sql_lines.append("\nCOMMIT;\n")

    # Add post-migration verification query block
    sql_lines.append("""-- ============================================================================
-- 4. VERIFICATION QUERY (Run this after COMMIT to verify row parity)
-- ============================================================================
SELECT 'events' AS table_name, COUNT(*) AS row_count, 101 AS expected FROM events
UNION ALL SELECT 'users', COUNT(*), 2 FROM users
UNION ALL SELECT 'student_profiles', COUNT(*), 2 FROM student_profiles
UNION ALL SELECT 'user_identities', COUNT(*), 2 FROM user_identities
UNION ALL SELECT 'user_sessions', COUNT(*), 11 FROM user_sessions
UNION ALL SELECT 'oauth_states', COUNT(*), 6 FROM oauth_states
UNION ALL SELECT 'notification_preferences', COUNT(*), 1 FROM notification_preferences
UNION ALL SELECT 'registration_actions', COUNT(*), 3 FROM registration_actions
UNION ALL SELECT 'registration_audit_logs', COUNT(*), 9 FROM registration_audit_logs
UNION ALL SELECT 'adapter_sync_logs', COUNT(*), 132 FROM adapter_sync_logs
UNION ALL SELECT 'notifications', COUNT(*), 65 FROM notifications
ORDER BY table_name;
""")

    content = "\n".join(sql_lines)

    # STRICT CREDENTIALS / SECRETS AUDIT
    forbidden_tokens = ["DATABASE_URL", "postgres://", "postgresql://", "supersecret", "SESSION_SECRET"]
    for tok in forbidden_tokens:
        if tok in content:
            raise ValueError(f"CRITICAL: Forbidden token '{tok}' found in generated SQL!")

    OUTPUT_SQL_PATH.write_text(content, encoding="utf-8")
    conn.close()

    hash_after = _sha256(DB_PATH)
    if hash_before != hash_after:
        raise RuntimeError("CRITICAL ERROR: Source SQLite database checksum changed! Read-only violation.")

    print(f"Generated PostgreSQL migration script: {OUTPUT_SQL_PATH}")
    print(f"Total tables: {len(summary_stats)}")
    print(f"Total rows to migrate: {total_rows}")
    for tbl, cnt in summary_stats:
        print(f"  {tbl:<28}: {cnt} rows")


if __name__ == "__main__":
    generate_migration_sql()
